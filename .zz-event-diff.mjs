import fs from "node:fs";
import mongoose from "mongoose";
import pg from "pg";
const env = fs.readFileSync(".env.local", "utf8");
await mongoose.connect(env.match(/^MONGODB_URI=(.*)$/m)[1].trim());
const db = mongoose.connection.db;
const client = new pg.Client({ connectionString: env.match(/^DATABASE_URL=(.*)$/m)[1].trim() });
await client.connect();
const mongoIds = new Set((await db.collection("events").find({}, { projection: { _id: 1 } }).toArray()).map((d) => d._id.toString()));
const pgRows = (await client.query(`select id, title, org, "createdAt" from events`)).rows;
console.log("только в Postgres:");
for (const r of pgRows) if (!mongoIds.has(r.id)) console.log("  ", r.id, "|", r.title, "|", r.startAt, "|", r.createdAt);
const pgIds = new Set(pgRows.map((r) => r.id));
console.log("только в Mongo:", [...mongoIds].filter((id) => !pgIds.has(id)).join(", ") || "(нет)");
await client.end();
await mongoose.disconnect();
